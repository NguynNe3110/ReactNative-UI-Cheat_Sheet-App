function lesson(
  category: string,
  id: string,
  title: string,
  demo: string,
  description: string,
  props: string,
  tip: string,
  exercise: string,
  kind: Kind = 'core',
  doc = id,
  platform: Lesson['platform'] = 'Android + iOS',
): Lesson {
  return {
    category,
    id,
    title,
    demo,
    description,
    props,
    tip,
    exercise,
    kind,
    platform,
    docs: doc.startsWith('https://')
      ? doc
      : `https://reactnative.dev/docs/${doc}`,
  };
}

